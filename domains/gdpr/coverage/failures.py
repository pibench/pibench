"""Failure table across every recorded wave run: the input for exploit planning.

  python3 domains/gdpr/coverage/failures.py

Reads coverage/results/wave<N>_{neutral,stress}.json (or .json.gz) and the
scenario files, and writes coverage/waves/failures.md: one row per scenario
that failed in at least one condition, with its label, main rules, primary
leaderboard column, pressure technique, the decision recorded in each
condition and the Tier-1 checks that failed. A condition still in progress
shows "-" for scenarios it has not reached.
"""

from __future__ import annotations

import json
import re
from collections import Counter
from datetime import date
from pathlib import Path

from results_io import read_results

ROOT = Path(__file__).resolve().parents[3]
COV = ROOT / "domains/gdpr/coverage"
OUT = COV / "waves/failures.md"


def _scenarios() -> dict[str, dict]:
    out = {}
    for f in sorted((ROOT / "scenarios/gdpr").glob("GDPR_W*.json")):
        sc = json.loads(f.read_text())
        pr = sc.get("user_simulation", {}).get("pressure")
        out[sc["meta"]["scenario_id"]] = {
            "label": sc.get("label"), "file": f.name,
            "rules": (sc.get("coverage") or {}).get("rules", []),
            "primary": (sc.get("leaderboard") or {}).get("primary", ""),
            "technique": (pr.get("technique") or ["-"])[0] if isinstance(pr, dict) else "-",
        }
    return out


def _passed(sim: dict) -> bool:
    return bool((sim.get("reward_info") or {}).get("all_passed"))


def _failed_checks(sim: dict) -> list[str]:
    return [o.get("outcome_id") for o in (sim.get("reward_info") or {}).get("outcome_results", [])
            if not o.get("passed") and o.get("type") not in ("NL_JUDGE", "NL_ASSERTION")]


def main() -> None:
    scen = _scenarios()
    waves = sorted({int(m.group(1)) for p in (COV / "results").glob("wave*_*.json*")
                    if (m := re.match(r"wave(\d+)_", p.name))})
    runs = {(w, c): {s["task_id"]: s for s in read_results(COV / f"results/wave{w}_{c}.json").get("simulations", [])}
            for w in waves for c in ("neutral", "stress")}
    rows, counts = [], Counter()
    for sid, m in scen.items():
        w = int(sid.split("_")[1][1:])
        n, s = runs.get((w, "neutral"), {}).get(sid), runs.get((w, "stress"), {}).get(sid)
        nf, sf = n is not None and not _passed(n), s is not None and not _passed(s)
        if not (nf or sf):
            continue
        counts["fail both" if nf and sf else "neutral only" if nf else "stress only"] += 1
        cell = lambda x: "-" if x is None else "PASS" if _passed(x) else \
            f"FAIL ({(x.get('reward_info') or {}).get('canonical_decision')})"
        checks = lambda x: ", ".join(_failed_checks(x)[:4]) if x else ""
        rows.append(f"| {sid} | {m['label']} | {', '.join(m['rules'][:3])} | {m['primary']} | {m['technique']} | "
                    f"{cell(n)} | {cell(s)} | {checks(n)} / {checks(s)} | {m['file']} |")
    run_lines = [f"- wave {w} {c}: {len(runs[(w, c)])} episodes" for w in waves for c in ("neutral", "stress")
                 if runs[(w, c)]]
    lines = [f"# Benchmark failures to exploit (generated {date.today().isoformat()})", "",
             "Generated by `domains/gdpr/coverage/failures.py` from the recorded runs (models and settings in "
             "`results/RUNS.md`). Runs read:", *run_lines, "",
             "| Scenario | Label | Main rules | Primary | Technique | Neutral | Stress | "
             "Failed Tier-1 checks (neutral / stress) | File |",
             "|---|---|---|---|---|---|---|---|---|", *rows, "",
             "Counts: " + ", ".join(f"{k} {v}" for k, v in counts.items()) + "."]
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{len(rows)} failing scenarios -> {OUT.relative_to(ROOT)} ({dict(counts)})")


if __name__ == "__main__":
    main()
